async def analyze_prescription_with_gemini(
    file_bytes: Optional[bytes] = None,
    mime_type: Optional[str] = None,
    text_content: Optional[str] = None
) -> Dict[str, Any]:
    """
    Directly queries Google Gemini API (with vision or text) to parse a prescription
    and generate the electronic prescription, tailored diet plan, and synchronized schedule.
    
    STRICT: NO hardcoded or fake fallbacks. Fails explicitly if Gemini cannot process it or if input is not a prescription.
    """
    if not file_bytes and not text_content:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="No prescription file or text was provided. Please upload an image/document or enter prescription details."
        )

    api_key = _get_api_key()

    # Build multimodal or text contents for Gemini
    user_parts = []
    
    if text_content and text_content.strip():
        user_parts.append({
            "text": f"{SYSTEM_PROMPT}\n\nPRESCRIPTION TEXT CONTENT TO EVALUATE:\n{text_content.strip()}"
        })
    else:
        user_parts.append({
            "text": f"{SYSTEM_PROMPT}\n\nPlease inspect this document carefully to determine if it is an authentic doctor prescription."
        })

    if file_bytes:
        normalized_mime = (mime_type or "image/jpeg").lower()
        if "pdf" in normalized_mime:
            normalized_mime = "application/pdf"
        elif "png" in normalized_mime:
            normalized_mime = "image/png"
        elif "webp" in normalized_mime:
            normalized_mime = "image/webp"
        else:
            normalized_mime = "image/jpeg"

        b64_data = base64.b64encode(file_bytes).decode("utf-8")
        user_parts.append({
            "inlineData": {
                "mimeType": normalized_mime,
                "data": b64_data
            }
        })

    payload = {
        "contents": [
            {
                "role": "user",
                "parts": user_parts
            }
        ],
        "generationConfig": {
            "temperature": 0.0,
            "maxOutputTokens": 2048,
            "responseMimeType": "application/json"
        }
    }

    last_error = None
    seen_models = set()

    async with httpx.AsyncClient(timeout=45.0) as client:
        for model in CANDIDATE_MODELS:
            if not model or model in seen_models:
                continue
            seen_models.add(model)
            
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
            try:
                logger.info("Calling Gemini model %s for prescription analysis...", model)
                res = await client.post(url, json=payload, headers={"Content-Type": "application/json"})
                
                if res.status_code == 200:
                    data = res.json()
                    candidates = data.get("candidates", [])
                    if not candidates:
                        raise ValueError("Gemini returned empty candidates.")
                    
                    parts = candidates[0].get("content", {}).get("parts", [])
                    raw_text = "".join(p.get("text", "") for p in parts if "text" in p).strip()
                    
                    # Clean any accidental markdown wrap
                    raw_text = re.sub(r"^```(?:json)?\s*", "", raw_text, flags=re.MULTILINE)
                    raw_text = re.sub(r"\s*```$", "", raw_text, flags=re.MULTILINE)
                    
                    parsed_json = json.loads(raw_text)
                    
                    # 1. Validation Gate: Reject non-prescriptions
                    is_valid = parsed_json.get("is_valid_prescription", True)
                    if is_valid is False:
                        rejection = parsed_json.get("rejection_reason") or "Uploaded document is not a medical prescription."
                        doc_type = parsed_json.get("document_type_detected") or "Non-prescription document"
                        raise HTTPException(
                            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                            detail=f"Invalid Prescription: {rejection} (Detected: {doc_type}). Please upload an authentic doctor's prescription."
                        )

                    # 2. Validate presence of actual medications
                    medicines = parsed_json.get("medicines", [])
                    if not isinstance(medicines, list) or len(medicines) == 0:
                        raise HTTPException(
                            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                            detail="No prescribed medications found. The document does not contain any readable medical prescription orders. Please upload a clear doctor's prescription."
                        )
                    
                    # 3. Ensure diet_plan and daily_schedule exist
                    if "diet_plan" not in parsed_json or not parsed_json["diet_plan"]:
                        raise ValueError("Gemini did not return a diet plan for this prescription.")
                    if "daily_schedule" not in parsed_json or not parsed_json["daily_schedule"]:
                        raise ValueError("Gemini did not return a daily schedule for this prescription.")

                    parsed_json["model_used"] = model
                    return parsed_json
                
                elif res.status_code in (503, 429):
                    logger.warning("Gemini model %s returned status %s. Failing over to next model in pool...", model, res.status_code)
                    last_error = f"Gemini model {model} high demand / throttled (status {res.status_code})"
                    continue
                else:
                    err_msg = res.text[:200]
                    logger.error("Gemini API error (%s) on model %s: %s", res.status_code, model, err_msg)
                    last_error = f"Gemini error {res.status_code}: {err_msg}"
                    break
            except HTTPException:
                # Re-raise explicit clinical validation exceptions directly
                raise
            except json.JSONDecodeError as jde:
                logger.error("Failed to parse Gemini JSON output: %s", jde)
                last_error = f"Malformed JSON from Gemini: {jde}"
                continue
            except Exception as exc:
                logger.warning("Exception calling Gemini model %s: %s", model, exc)
                last_error = str(exc)
                continue

    # NO FALLBACK DATA ALLOWED: Fail explicitly with descriptive error
    raise HTTPException(
        status_code=status.HTTP_502_BAD_GATEWAY,
        detail=f"Unable to extract electronic prescription using Gemini AI: {last_error or 'Upstream service unavailable'}. Please verify your prescription image is clear and try again."
    )
